import { describe, expect, it } from "vitest";
import { roundDates, roundLabel } from "./round-label";

// 시각은 UTC로 적는다. 10:30Z = 서울 저녁 7:30
describe("회차 이름 뒤 날짜", () => {
  it("이틀이면 가운뎃점으로 잇고 같은 달은 한 번만 쓴다", () => {
    expect(roundLabel("11월 첫째 주 저녁", ["2026-11-06T10:30:00Z", "2026-11-07T10:30:00Z", "2026-11-06T11:00:00Z"])).toBe("11월 첫째 주 저녁 (11월 6일(금)·7일(토))");
  });
  it("사흘 이상이면 처음~끝으로 줄인다(순서가 섞여 들어와도)", () => {
    expect(roundDates(["2026-11-08T10:30:00Z", "2026-11-06T10:30:00Z", "2026-11-07T10:30:00Z"])).toBe("11월 6일(금)~8일(일)");
  });
  it("달이 넘어가면 두 달 다 쓴다", () => {
    expect(roundDates(["2026-10-30T10:30:00Z", "2026-10-31T10:30:00Z", "2026-11-01T10:30:00Z"])).toBe("10월 30일(금)~11월 1일(일)");
    expect(roundDates(["2026-10-31T10:30:00Z", "2026-11-01T10:30:00Z"])).toBe("10월 31일(토)·11월 1일(일)");
  });
  it("서울 날짜로 센다: UTC로는 전날이어도 서울에서 다음 날이면 그날", () => {
    // 2026-11-06T16:00Z = 서울 11월 7일(토) 새벽 1시
    expect(roundDates(["2026-11-06T16:00:00Z"])).toBe("11월 7일(토)");
  });
  it("일정이 없으면 이름만", () => {
    expect(roundLabel("11월 둘째 주 저녁", [])).toBe("11월 둘째 주 저녁");
  });
});
